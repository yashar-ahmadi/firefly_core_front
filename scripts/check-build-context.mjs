// `pnpm typecheck`'s second step: the production build's type check, run on the Docker build
// context alone (scripts/build-context.mjs: what `.dockerignore` lets through, so no `tests/`,
// no test runner config). The image's `next build` type-checks the project of
// `typescript.tsconfigPath` (next.config.ts) with only those files present; a file there that
// imports a test-only one (vitest.setup.ts → tests/unit/support/network-guard broke the image
// once) fails here, before any push, as it would in `docker build`.
//
//   node scripts/check-build-context.mjs [tsconfig]   (default: tsconfig.build.json)
//
// The context is copied to a temporary folder (removed after) beside a link to this checkout's
// node_modules (the image installs its own); `next-env.d.ts` and `.next/types` are generated by
// `next build` itself and are not needed to type-check the sources. Stricter than the build's own
// check in one way: an import kept for its side effects alone must resolve as well.

import { spawnSync } from 'node:child_process'
import { cpSync, mkdirSync, mkdtempSync, rmSync, symlinkSync } from 'node:fs'
import { createRequire } from 'node:module'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { contextFiles } from './build-context.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const project = process.argv[2] ?? 'tsconfig.build.json'
const tsc = createRequire(import.meta.url).resolve('typescript/bin/tsc')

const staged = mkdtempSync(path.join(os.tmpdir(), 'ff-build-context-'))
let status = 1
try {
  const files = contextFiles(root)
  for (const file of files) {
    const to = path.join(staged, file)
    mkdirSync(path.dirname(to), { recursive: true })
    cpSync(path.join(root, file), to)
  }
  symlinkSync(path.join(root, 'node_modules'), path.join(staged, 'node_modules'), 'dir')
  const result = spawnSync(
    process.execPath,
    // An import kept only for its side effects is resolved too (tsc skips it by default): the
    // image's bundler fails on one it cannot find, as on any other.
    [
      tsc,
      '--noEmit',
      '--incremental',
      'false',
      '--noUncheckedSideEffectImports',
      '--project',
      project,
    ],
    { cwd: staged, stdio: 'inherit' },
  )
  status = result.status ?? 1
  if (status === 0) {
    console.log(
      `[build context] ${project} type-checks with the ${files.length} files the image gets`,
    )
  } else {
    console.error(
      `[build context] the production build's type check (${project}) fails with only the files ` +
        '.dockerignore lets into the image: a file it checks needs one the image never gets ' +
        '(tests/, a test runner config…). Keep test-only code out of what the build checks.',
    )
  }
} finally {
  rmSync(staged, { recursive: true, force: true })
}
process.exit(status)
